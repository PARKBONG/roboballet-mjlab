"""Where the code finds its files at run time.

Two places. The package itself holds what is in git: the sphere arm, the small scene pools and the
frozen static boxes. The data directory holds what fetch-data downloads: the original's MuJoCo world,
its start states and paper tasksets from Zenodo record 16546403, and the large scene pools from this
repository's release. Its layout:

  mujoco_world/                 Zenodo, the original's data/mujoco_world
  paper_test_tasksets/          Zenodo, the original's data/paper_test_tasksets
  start_states/{R}r_{T}t_30o.pb Zenodo, the original's data/start_states
  scenes/{R}r_{T}t_30o_{split}.pt  release assets, and where gen_scenes writes

The data directory is $ROBOBALLET_DATA if set, else data/ in the clone, beside src/. The train, play,
eval and fetch-data commands set ROBOBALLET_DATA from --data-dir before anything here is imported.
"""

from __future__ import annotations

import os
from pathlib import Path

DATA_ENV = 'ROBOBALLET_DATA'
PACKAGE_DIR = Path(__file__).resolve().parent
PACKAGE_DATA = PACKAGE_DIR / 'data'
# src/roboballet_mjlab -> the clone. Right for an editable install, the one uv sync makes.
DEFAULT_DATA_DIR = PACKAGE_DIR.parents[1] / 'data'


def data_dir() -> Path:
  """Read on every call, so a command can set the environment variable first."""
  return Path(os.environ.get(DATA_ENV) or DEFAULT_DATA_DIR).expanduser().resolve()


def scene_pool(name: str) -> Path:
  """A pool by name, without .pt: the data directory's copy if it has one, else the package's.

  The data directory wins so that a pool regenerated by gen_scenes replaces the one in git. A pool
  found in neither place returns the data directory's path, for the error message.
  """
  downloaded = data_dir() / 'scenes' / f'{name}.pt'
  packaged = PACKAGE_DATA / 'scenes' / f'{name}.pt'
  if not downloaded.exists() and packaged.exists():
    return packaged
  return downloaded
